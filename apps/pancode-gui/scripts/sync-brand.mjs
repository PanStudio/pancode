// Build-time projection; the installed app reads only its bundled assets.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { pnpmArgv } from "../../../scripts/pnpm.mjs";
import { fontFiles } from "../../../site/tokens.mjs";

const file = (path) => new URL(path, import.meta.url);
const source = await readFile(file("../../../site/design-system.json"));
const design = JSON.parse(source);
const roles = {
	paper: "paper",
	surface: "paper-raised",
	"surface-sunken": "paper-sunk",
	overlay: "paper-overlay",
	well: "paper-sunk",
	raised: "paper-raised",
	ink: "ink",
	"ink-strong": "ink",
	"ink-muted": "muted",
	"ink-subtle": "muted",
	"ink-faint": "faint",
	line: "line",
	"line-strong": "line-control",
	accent: "accent",
	"accent-strong": "accent-hover",
	"accent-soft": "accent-soft",
	"on-accent": "on-accent",
	focus: "focus",
	"focus-halo": "paper",
	"primary-fill": "fill",
	"primary-hover": "fill-hover",
	"on-primary": "on-fill",
	selection: "selection",
	"on-selection": "on-selection",
	secondary: "secondary",
	"reason-fg": "ink-soft",
	"reason-tint": "paper-sunk",
	"reason-line": "line-control",
	"action-fg": "warning",
	"action-tint": "warning-soft",
	"action-line": "warning",
};
for (const [tone, role] of Object.entries({
	neutral: "muted",
	unverified: "muted",
	running: "info",
	success: "success",
	warn: "warning",
	fail: "error",
})) {
	roles[`status-${tone}-fg`] = role;
	roles[`status-${tone}-tint`] = role === "muted" ? "paper-sunk" : `${role}-soft`;
	roles[`status-${tone}-line`] = role === "muted" ? "line-control" : role;
}
const hex = (key) => {
	if (!design.palette[key]) throw new Error(`Missing brand colour: ${key}`);
	return design.palette[key];
};
const lines = (tokens) =>
	Object.entries(tokens)
		.map(([key, value]) => `\t--${key}: ${value};`)
		.join("\n");
const theme = (name) => {
	const scheme = design.themes[name];
	return lines({
		...Object.fromEntries(Object.entries(roles).map(([key, role]) => [key, hex(scheme[role])])),
		...Object.fromEntries(
			Object.entries(scheme)
				.filter(([role]) => role.startsWith("viz-"))
				.map(([key, color]) => [key, hex(color)]),
		),
		...Object.fromEntries(
			["raised", "panel", "float"].map((level, i) => [`shadow-${level}`, design.elevation[name][i + 1]]),
		),
		"color-scrim": name === "dark" ? "72%" : "52%",
	});
};
// Every palette colour the mark's cuts name, so PancodeMark paints the artwork from the palette, not from copies.
const markColours = new Set();
for (const cut of ["pancode-mark", "pancode-mark-light", "pancode-mark-small"])
	for (const [, name] of (await readFile(file(`../../../assets/brand/${cut}.svg`), "utf8")).matchAll(
		/var\(--palette-([\w-]+)/g,
	))
		markColours.add(name);
markColours.delete("black");
markColours.delete("green400");
const { code, type } = design;
const family = (role) => `"${type.families[role].family}", ${type.families[role].fallback}`;
const codeColors = {
	"stage-black": "black",
	"code-paper": code.surface,
	"code-surface": code.sunk,
	"code-ink": code.text,
	"code-ink-muted": code.muted,
	"code-line": code.border,
	"code-gutter": code.muted,
	"code-signal": code.syntax.prompt,
	"code-error-tint": design.themes.dark["error-soft"],
	...Object.fromEntries(Object.entries(code.syntax).map(([key, color]) => [`syntax-${key}`, color])),
	"syntax-punctuation": code.syntax.operator,
	"syntax-deleted": code.syntax.removed,
	"syntax-inserted": code.syntax.added,
};
const css = `/* Generated by scripts/sync-brand.mjs from the canonical site export. */
${type.faces.map(({ family, style, weight, file }) => `@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url("/fonts/${file}") format("woff2"); }`).join("\n")}
:root {
	--pancode-black: ${hex("black")};
	--pancode-green400: ${hex("green400")};
	--pancode-pine1: ${hex("pine1")};
${lines(Object.fromEntries([...markColours].sort().map((name) => [`pancode-${name}`, hex(name)])))}
	--font-ui: ${family("text")};
	--font-editorial: ${family("display")};
	--font-mono: ${family("mono")};
	--radius-sm: ${design.radius.sm};
	--radius-md: ${design.radius.md};
	--radius-xs: ${design.radius.xs};
	--radius-lg: ${design.radius.lg};
${lines(Object.fromEntries(Object.entries(codeColors).map(([key, color]) => [key, hex(color)])))}
${theme("light")}
	--motion-fast: ${design.motion.fast};
	--motion-base: ${design.motion.base};
	--motion-entry: ${design.motion.entry};
	--motion-feedback: ${design.motion.feedback};
	--motion-distance: ${design.motion.distance};
	--motion-stagger: ${design.motion.stagger};
	--ease-standard: ${design.motion.ease};
	--ease-emphasis: ${design.motion.ease};
}
:root[data-theme="dark"] {
${theme("dark")}
}
@media (prefers-color-scheme: dark) {
	:root:not([data-theme="light"]) {
${theme("dark")}
	}
}
`;
const target = file("../client/design/brand.css");
const [pnpm, formatArgs] = pnpmArgv(["exec", "biome", "format", "--stdin-file-path", fileURLToPath(target)]);
const formatted = execFileSync(pnpm, formatArgs, {
	input: css,
	encoding: "utf8",
	cwd: fileURLToPath(file("../")),
});
if (process.argv.includes("--check")) {
	if ((await readFile(target, "utf8")) !== formatted)
		throw new Error("GUI brand tokens drifted. Run scripts/sync-brand.mjs.");
	const provenance = JSON.parse(await readFile(file("../client/public/brand/provenance.json"), "utf8"));
	if (provenance.projection.designSha256 !== createHash("sha256").update(source).digest("hex"))
		throw new Error("GUI brand snapshot is stale. Export the canonical brand again.");
	for (const [name, hash] of Object.entries(provenance.projection.sha256))
		if (
			createHash("sha256")
				.update(await readFile(file(`../client/public/${name}`)))
				.digest("hex") !== hash
		)
			throw new Error(`GUI mark projection drifted: ${name}`);
	for (const name of fontFiles(design))
		if (
			!(await readFile(file(`../client/public/fonts/${name}`))).equals(
				await readFile(file(`../../../site/assets/fonts/${name}`)),
			)
		)
			throw new Error(`GUI canonical font or notice differs: ${name}`);
	const mark = provenance.assets.find((asset) => asset.name === "pancode-mark");
	if (
		!mark ||
		mark.sha256 !==
			createHash("sha256")
				.update(await readFile(file("../../../site/assets/brand/pancode-mark.png")))
				.digest("hex")
	)
		throw new Error("GUI canonical mark provenance differs.");
} else await writeFile(target, formatted);
