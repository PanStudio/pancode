/**
 * Builds the MCP server a first-party plugin carries as source. A plugin
 * under `hub/packs/plugins/<name>/` with `src/main.ts` gets two generated
 * files at its root, both committed so the folder is complete for any host:
 *
 * - `server.mjs`: `src/main.ts` bundled by esbuild with the SDK inlined, so it
 *   runs under plain `node` with no install step.
 * - `mcp.json`: the PanCode declaration launching it as
 *   `node ${PLUGIN_ROOT}/server.mjs`, with each tool's action class and path
 *   arguments from the server's `policyManifest` and, as `envVars`, the
 *   variables `src/server.ts` exports as `environment`.
 *
 * `src/server.ts` exports the `server` that `src/main.ts` serves. Run through
 * `pnpm run hub:pin`, before the packs are pinned; `pnpm run hub:check` builds
 * in memory and reports a committed file that differs.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { policyManifest, type ToolServer } from "pancode/sdk/tool";
import { parsePassedVariables } from "../src/domains/gateway/mcp/passed-environment.js";

export const PLUGIN_SERVER_FILE = "server.mjs";
const ENTRY = path.join("src", "main.ts");
const SERVER_MODULE = path.join("src", "server.ts");

/** The bundle's first lines: the SDK it inlines is Apache-2.0, the rest is PanCode's. */
const BANNER = [
	"// SPDX-License-Identifier: LicenseRef-PanCode-1.0 AND Apache-2.0",
	"// SPDX-FileCopyrightText: 2026 Anthony Kougkas",
	"// Generated by `pnpm run hub:pin` from src/ and the PanCode SDK (packages/sdk, Apache-2.0); edit src/ and pin again.",
].join("\n");

export interface PluginServerBuild {
	/** The files the plugin should hold, path relative to the repository root, and their bytes. */
	files: Array<{ path: string; content: string }>;
}

export interface PluginServerResult {
	/** Files written (pin) or differing from what was committed (check). */
	changed: string[];
	errors: string[];
}

function pluginDirectories(root: string): string[] {
	const plugins = path.join(root, "hub", "packs", "plugins");
	if (!existsSync(plugins)) return [];
	return readdirSync(plugins, { withFileTypes: true })
		.filter((entry) => entry.isDirectory() && existsSync(path.join(plugins, entry.name, ENTRY)))
		.map((entry) => path.join(plugins, entry.name))
		.sort();
}

/** Formats generated JSON the way `biome check` wants it, so the lint gate accepts the committed file. */
export function biomeJson(root: string, file: string, value: unknown): string {
	const biome = createRequire(path.join(root, "package.json")).resolve("@biomejs/biome/bin/biome");
	const formatted = spawnSync(process.execPath, [biome, "format", `--stdin-file-path=${file}`], {
		cwd: root,
		input: `${JSON.stringify(value, null, "\t")}\n`,
		encoding: "utf8",
	});
	if (formatted.status !== 0) throw new Error(`biome format ${file}: ${formatted.stderr.trim()}`);
	return formatted.stdout;
}

/** The PanCode `mcp.json` that launches the built server. */
export function pluginMcpDeclaration(server: ToolServer, environment: ReadonlyArray<string>): unknown {
	const manifest = policyManifest(server);
	const toolPathArguments = Object.fromEntries(
		manifest.tools
			.filter((tool) => Object.keys(tool.pathArguments).length > 0)
			.map((tool) => [tool.name, tool.pathArguments]),
	);
	return {
		mcpServers: {
			[server.id]: {
				type: "stdio",
				command: "node",
				args: [`\${PLUGIN_ROOT}/${PLUGIN_SERVER_FILE}`],
				...(environment.length > 0 ? { envVars: [...environment].sort() } : {}),
				toolActionClasses: Object.fromEntries(manifest.tools.map((tool) => [tool.name, tool.actionClass])),
				...(Object.keys(toolPathArguments).length > 0 ? { toolPathArguments } : {}),
			},
		},
	};
}

async function buildOne(root: string, directory: string): Promise<PluginServerBuild> {
	const bundled = await build({
		absWorkingDir: root,
		entryPoints: [path.join(directory, ENTRY)],
		outfile: path.join(directory, PLUGIN_SERVER_FILE),
		bundle: true,
		platform: "node",
		format: "esm",
		target: "node22",
		tsconfig: path.join(root, "tsconfig.json"),
		banner: { js: BANNER },
		legalComments: "none",
		charset: "utf8",
		write: false,
		logLevel: "silent",
	});
	const output = bundled.outputFiles[0];
	if (output === undefined) throw new Error(`${path.relative(root, directory)}: esbuild wrote no output`);
	const loaded = (await import(pathToFileURL(path.join(directory, SERVER_MODULE)).href)) as {
		server?: ToolServer;
		environment?: ReadonlyArray<string>;
	};
	if (loaded.server === undefined)
		throw new Error(`${path.relative(root, directory)}/${SERVER_MODULE} exports no server`);
	const environment =
		loaded.environment === undefined
			? []
			: parsePassedVariables(loaded.environment, `${path.relative(root, directory)}/${SERVER_MODULE} environment`);
	if (typeof environment === "string") throw new Error(environment);
	const mcpFile = path.join(directory, "mcp.json");
	return {
		files: [
			{ path: path.relative(root, output.path), content: output.text },
			{
				path: path.relative(root, mcpFile),
				content: biomeJson(root, mcpFile, pluginMcpDeclaration(loaded.server, environment)),
			},
		],
	};
}

/** Builds every plugin server; `check` writes nothing and reports each committed file that differs. */
export async function buildPluginServers(options: { root: string; check: boolean }): Promise<PluginServerResult> {
	const changed: string[] = [];
	const errors: string[] = [];
	for (const directory of pluginDirectories(options.root)) {
		let built: PluginServerBuild;
		try {
			built = await buildOne(options.root, directory);
		} catch (error) {
			errors.push(`${path.relative(options.root, directory)}: ${error instanceof Error ? error.message : String(error)}`);
			continue;
		}
		for (const file of built.files) {
			const absolute = path.join(options.root, file.path);
			const current = existsSync(absolute) ? readFileSync(absolute, "utf8") : null;
			if (current === file.content) continue;
			changed.push(file.path);
			if (!options.check) writeFileSync(absolute, file.content);
		}
	}
	return { changed, errors };
}
