/**
 * Build step: pack the TypeScript source PanCode never reads at runtime, under
 * src/ and every packages/<name>/src/, into dist/assets/source.pack and write a
 * .npmignore in each of those source roots so npm leaves those files out of the
 * tarball. `read` and `code_nav` open packed members on demand
 * through src/core/source-pack.ts, which owns the reader side of this layout.
 * Runs after tsup and before the code map, which indexes packed members as
 * shipped files.
 */
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { brotliCompress, constants as zlibConstants } from "node:zlib";
import { SOURCE_PACK_RELATIVE_PATH } from "../src/core/source-pack.js";
import { reportBuildStage } from "./build-output.js";
import { planSourcePack, sourceRoots } from "./source-pack-plan.mjs";

const MAGIC = "PANSRC01";
const brotliCompressAsync = promisify(brotliCompress);

/**
 * The 8-byte magic, a u32 LE index length, the JSON index, then one brotli
 * stream per member. Members compress concurrently on the libuv pool; the
 * layout follows the sorted path order, so the bytes match a serial encode.
 */
async function encodeSourcePack(paths: ReadonlyArray<string>, readMember: (path: string) => Buffer): Promise<Buffer> {
	const members = await Promise.all(
		[...paths].sort().map(async (path) => {
			const bytes = readMember(path);
			const blob = await brotliCompressAsync(bytes, {
				params: {
					[zlibConstants.BROTLI_PARAM_QUALITY]: 11,
					[zlibConstants.BROTLI_PARAM_SIZE_HINT]: bytes.length,
				},
			});
			return { path, size: bytes.length, blob };
		}),
	);
	const files: Array<{ path: string; offset: number; length: number; size: number }> = [];
	let offset = 0;
	for (const { path, size, blob } of members) {
		files.push({ path, offset, length: blob.length, size });
		offset += blob.length;
	}
	const index = Buffer.from(JSON.stringify({ version: 1, files }), "utf8");
	const header = Buffer.alloc(MAGIC.length + 4);
	header.write(MAGIC, 0, "latin1");
	header.writeUInt32LE(index.length, MAGIC.length);
	return Buffer.concat([header, index, ...members.map((member) => member.blob)]);
}

const root = fileURLToPath(new URL("..", import.meta.url));
const startedAt = performance.now();
const plan = planSourcePack(root);
const target = join(root, SOURCE_PACK_RELATIVE_PATH);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, await encodeSourcePack(plan.packed, (path) => readFileSync(join(root, path))));
// npm honors a nested .npmignore even under a `files` allowlist. One is
// generated in each source root beside the pack so the two always agree, and
// each is gitignored.
for (const sourceRoot of sourceRoots(root)) {
	const prefix = `${sourceRoot}/`;
	const lines = plan.packed.filter((path) => path.startsWith(prefix)).map((path) => `/${path.slice(prefix.length)}`);
	writeFileSync(
		join(root, sourceRoot, ".npmignore"),
		`# Generated by scripts/build-source-pack.ts: these files ship inside ${SOURCE_PACK_RELATIVE_PATH}.\n${lines.join("\n")}\n`,
	);
}
reportBuildStage("Source pack", startedAt, statSync(target).size);
